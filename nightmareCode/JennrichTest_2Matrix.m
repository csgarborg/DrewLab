function [chi2, p_val]=JennrichTest_2Matrix(R1, R2,n1,n2)
%R1, R2 - correlation matricies
%n1, n2 - sample size that r1,r2 are based on
%chi2 - chisquared value
% p value - significance of the chi-squared test
%adapted from Robert I. Jennrich (1970): An Asymptotic χ
%2 Test for the Equality of  Two Correlation Matrices, Journal of the American Statistical 
% Association, 65:330, 904-912 doi: 10.1080/01621459.1970.10481133
% sept 2 2026, patrick drew 

dd=length(R1);
dof=dd*(dd-1)/2;%degrees of freeedom
R_bar=(n1*R1+n2*R2)/(n1+n2);
Rinv=inv(R_bar);
c=(n1*n2)/(n1+n2);
Z=sqrt(c)*Rinv*(R1-R2);
S=R_bar.*inv(R_bar)+eye(size(R_bar));
Sinv=inv(S);
chi2=0.5*trace(Z*Z)-diag(Z)'*Sinv*diag(Z);
p_val=1-chi2cdf(chi2,dof);


